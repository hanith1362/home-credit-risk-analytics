SELECT
    CUSTOMER_ID,

    -- Account information
    COUNT(DISTINCT PREVIOUS_APPLICATION_ID)
        AS TOTAL_CREDIT_CARD_ACCOUNTS,

    -- Balance information
    AVG(CURRENT_BALANCE)
        AS AVG_CREDIT_CARD_BALANCE,

    MAX(CURRENT_BALANCE)
        AS MAX_CREDIT_CARD_BALANCE,

    -- Credit limit
    AVG(CREDIT_LIMIT)
        AS AVG_CREDIT_LIMIT,

    MAX(CREDIT_LIMIT)
        AS MAX_CREDIT_LIMIT,

    -- Average monthly utilization
    AVG(
        {{credit_utilization('CURRENT_BALANCE', 'CREDIT_LIMIT')}}
    ) AS AVG_CREDIT_UTILIZATION,

    -- Drawing behavior
    SUM(COALESCE(ATM_DRAWINGS_AMOUNT, 0))
        AS TOTAL_ATM_DRAWINGS,

    SUM(COALESCE(POS_DRAWINGS_AMOUNT, 0))
        AS TOTAL_POS_DRAWINGS,

    SUM(COALESCE(OTHER_DRAWINGS_AMOUNT, 0))
        AS TOTAL_OTHER_DRAWINGS,

    SUM(COALESCE(TOTAL_DRAWINGS_AMOUNT, 0))
        AS TOTAL_DRAWINGS,

    -- Payment behavior
    SUM(COALESCE(TOTAL_PAYMENT_AMOUNT, 0))
        AS TOTAL_PAYMENTS,

    AVG(CURRENT_PAYMENT_AMOUNT)
        AS AVG_CURRENT_PAYMENT,

    AVG(MINIMUM_INSTALLMENT_AMOUNT)
        AS AVG_MINIMUM_INSTALLMENT,

    -- Receivable information
    AVG(RECEIVABLE_PRINCIPAL)
        AS AVG_RECEIVABLE_PRINCIPAL,

    AVG(RECEIVABLE_AMOUNT)
        AS AVG_RECEIVABLE_AMOUNT,

    AVG(TOTAL_RECEIVABLE_AMOUNT)
        AS AVG_TOTAL_RECEIVABLE,

    -- Transaction frequency
    SUM(COALESCE(ATM_DRAWINGS_COUNT, 0))
        AS TOTAL_ATM_DRAWING_TRANSACTIONS,

    SUM(COALESCE(TOTAL_DRAWINGS_COUNT, 0))
        AS TOTAL_DRAWING_TRANSACTIONS,

    SUM(COALESCE(POS_DRAWINGS_COUNT, 0))
        AS TOTAL_POS_DRAWING_TRANSACTIONS,

    -- Delinquency
    COUNT_IF(DAYS_PAST_DUE > 0)
        AS OVERDUE_MONTH_RECORDS,

    MAX(DAYS_PAST_DUE)
        AS MAX_DAYS_PAST_DUE,

    MAX(DAYS_PAST_DUE_TOLERANCE)
        AS MAX_DAYS_PAST_DUE_TOLERANCE,

    -- Monthly information
    COUNT(DISTINCT MONTH_OFFSET)
        AS TOTAL_MONTHLY_RECORDS,

    -- Ingestion tracking
    MAX(INSERTED_AT) AS LATEST_INSERTED_AT,
    MAX(UPDATED_AT) AS LATEST_UPDATED_AT

FROM {{ ref('stg_credit_card_balance') }}

GROUP BY CUSTOMER_ID
