WITH PAYMENT_DETAILS AS (

    SELECT
        CUSTOMER_ID,
        PREVIOUS_APPLICATION_ID,
        INSTALLMENT_VERSION,
        INSTALLMENT_NUMBER,
        SCHEDULED_PAYMENT_DAY,
        ACTUAL_PAYMENT_DAY,
        SCHEDULED_PAYMENT_AMOUNT,
        ACTUAL_PAYMENT_AMOUNT,

        ACTUAL_PAYMENT_DAY - SCHEDULED_PAYMENT_DAY
            AS PAYMENT_DELAY_DAYS,

        GREATEST(
            COALESCE(SCHEDULED_PAYMENT_AMOUNT, 0)
            - COALESCE(ACTUAL_PAYMENT_AMOUNT, 0),
            0
        ) AS UNPAID_AMOUNT,

        INSERTED_AT,
        UPDATED_AT

    FROM {{ ref('stg_installments_payments') }}

)

SELECT
    CUSTOMER_ID,

    COUNT(*) AS TOTAL_INSTALLMENT_RECORDS,

    COUNT(DISTINCT PREVIOUS_APPLICATION_ID)
        AS TOTAL_LOANS_WITH_INSTALLMENTS,

    SUM(COALESCE(SCHEDULED_PAYMENT_AMOUNT, 0))
        AS TOTAL_SCHEDULED_AMOUNT,

    SUM(COALESCE(ACTUAL_PAYMENT_AMOUNT, 0))
        AS TOTAL_ACTUAL_PAYMENT_AMOUNT,

    AVG(PAYMENT_DELAY_DAYS)
        AS AVG_PAYMENT_DELAY_DAYS,

    COUNT_IF(PAYMENT_DELAY_DAYS > 0)
        AS LATE_PAYMENT_COUNT,

    COUNT_IF(PAYMENT_DELAY_DAYS <= 0)
        AS ON_TIME_OR_EARLY_PAYMENT_COUNT,

    SUM(UNPAID_AMOUNT)
        AS TOTAL_UNPAID_AMOUNT,

    MAX(PAYMENT_DELAY_DAYS)
        AS MAXIMUM_PAYMENT_DELAY_DAYS,

    MAX(INSERTED_AT) AS LATEST_INSERTED_AT,
    MAX(UPDATED_AT) AS LATEST_UPDATED_AT

FROM PAYMENT_DETAILS

GROUP BY CUSTOMER_ID
