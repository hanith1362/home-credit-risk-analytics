SELECT
    CUSTOMER_ID,
    -- Loan account information
    COUNT(DISTINCT PREVIOUS_APPLICATION_ID)
        AS TOTAL_POS_CASH_LOANS,
    -- Installment information
    SUM(COALESCE(TOTAL_INSTALLMENTS, 0))
        AS TOTAL_INSTALLMENTS,
    SUM(COALESCE(REMAINING_INSTALLMENTS, 0))
        AS TOTAL_REMAINING_INSTALLMENTS,
    AVG(REMAINING_INSTALLMENTS)
        AS AVG_REMAINING_INSTALLMENTS,
    -- Delinquency information
    COUNT_IF(DAYS_PAST_DUE > 0)
        AS OVERDUE_RECORD_COUNT,
    MAX(DAYS_PAST_DUE)
        AS MAX_DAYS_PAST_DUE,
    COUNT_IF(DAYS_PAST_DUE_TOLERANCE > 0)
        AS SIGNIFICANT_OVERDUE_RECORD_COUNT,
    MAX(DAYS_PAST_DUE_TOLERANCE)
        AS MAX_DAYS_PAST_DUE_TOLERANCE,
    -- Contract status
    COUNT_IF(CONTRACT_STATUS = 'Active')
        AS ACTIVE_CONTRACT_RECORDS,
    COUNT_IF(CONTRACT_STATUS = 'Completed')
        AS COMPLETED_CONTRACT_RECORDS,
    -- Ingestion tracking
    MAX(INSERTED_AT) AS LATEST_INSERTED_AT,
    MAX(UPDATED_AT) AS LATEST_UPDATED_AT

FROM {{ ref('stg_pos_cash_balance') }}

GROUP BY CUSTOMER_ID
