SELECT
    -- Customer information
    A.CUSTOMER_ID,
    A.DEFAULT_FLAG,
    A.ANNUAL_INCOME,
    A.CREDIT_AMOUNT,
    A.ANNUITY_AMOUNT,
    A.GOODS_PRICE,
    A.AGE,

    -- External bureau credit history
    COALESCE(B.TOTAL_BUREAU_ACCOUNTS, 0) AS TOTAL_BUREAU_ACCOUNTS,
    COALESCE(B.ACTIVE_BUREAU_ACCOUNTS, 0) AS ACTIVE_BUREAU_ACCOUNTS,
    COALESCE(B.CLOSED_BUREAU_ACCOUNTS, 0) AS CLOSED_BUREAU_ACCOUNTS,
    COALESCE(B.TOTAL_BUREAU_CREDIT, 0) AS TOTAL_BUREAU_CREDIT,
    COALESCE(B.TOTAL_BUREAU_OUTSTANDING_DEBT, 0) AS TOTAL_BUREAU_OUTSTANDING_DEBT,
    COALESCE(B.TOTAL_BUREAU_OVERDUE_AMOUNT, 0) AS TOTAL_BUREAU_OVERDUE_AMOUNT,
    COALESCE(B.MAX_BUREAU_OVERDUE_AMOUNT, 0) AS MAX_BUREAU_OVERDUE_AMOUNT,

    -- Previous loan applications
    COALESCE(P.TOTAL_PREVIOUS_APPLICATIONS, 0) AS TOTAL_PREVIOUS_APPLICATIONS,
    COALESCE(P.APPROVED_APPLICATIONS, 0) AS APPROVED_APPLICATIONS,
    COALESCE(P.REFUSED_APPLICATIONS, 0) AS REFUSED_APPLICATIONS,
    COALESCE(P.TOTAL_REQUESTED_AMOUNT, 0) AS TOTAL_REQUESTED_AMOUNT,
    COALESCE(P.TOTAL_APPROVED_CREDIT, 0) AS TOTAL_APPROVED_CREDIT,
    COALESCE(P.AVG_REQUESTED_AMOUNT, 0) AS AVG_REQUESTED_AMOUNT,
    COALESCE(P.AVG_ANNUITY_AMOUNT, 0) AS AVG_ANNUITY_AMOUNT,
    COALESCE(P.AVG_PAYMENT_COUNT, 0) AS AVG_PAYMENT_COUNT,

    -- Installment payment behavior
    COALESCE(I.TOTAL_INSTALLMENT_RECORDS, 0) AS TOTAL_INSTALLMENT_RECORDS,
    COALESCE(I.TOTAL_LOANS_WITH_INSTALLMENTS, 0) AS TOTAL_LOANS_WITH_INSTALLMENTS,
    COALESCE(I.TOTAL_SCHEDULED_AMOUNT, 0) AS TOTAL_SCHEDULED_AMOUNT,
    COALESCE(I.TOTAL_ACTUAL_PAYMENT_AMOUNT, 0) AS TOTAL_ACTUAL_PAYMENT_AMOUNT,
    COALESCE(I.AVG_PAYMENT_DELAY_DAYS, 0) AS AVG_PAYMENT_DELAY_DAYS,
    COALESCE(I.LATE_PAYMENT_COUNT, 0) AS LATE_PAYMENT_COUNT,
    COALESCE(I.ON_TIME_OR_EARLY_PAYMENT_COUNT, 0) AS ON_TIME_OR_EARLY_PAYMENT_COUNT,
    COALESCE(I.TOTAL_UNPAID_AMOUNT, 0) AS TOTAL_UNPAID_AMOUNT,
    COALESCE(I.MAXIMUM_PAYMENT_DELAY_DAYS, 0) AS MAXIMUM_PAYMENT_DELAY_DAYS,

    -- POS and cash loan behavior
    COALESCE(POS.TOTAL_POS_CASH_LOANS, 0) AS TOTAL_POS_CASH_LOANS,
    COALESCE(POS.TOTAL_INSTALLMENTS, 0) AS TOTAL_INSTALLMENTS,
    COALESCE(POS.TOTAL_REMAINING_INSTALLMENTS, 0) AS TOTAL_REMAINING_INSTALLMENTS,
    COALESCE(POS.AVG_REMAINING_INSTALLMENTS, 0) AS AVG_REMAINING_INSTALLMENTS,
    COALESCE(POS.OVERDUE_RECORD_COUNT, 0) AS OVERDUE_RECORD_COUNT,
    COALESCE(POS.MAX_DAYS_PAST_DUE, 0) AS MAX_DAYS_PAST_DUE,
    COALESCE(POS.SIGNIFICANT_OVERDUE_RECORD_COUNT, 0) AS SIGNIFICANT_OVERDUE_RECORD_COUNT,
    COALESCE(POS.MAX_DAYS_PAST_DUE_TOLERANCE, 0) AS MAX_DAYS_PAST_DUE_TOLERANCE,
    COALESCE(POS.ACTIVE_CONTRACT_RECORDS, 0) AS ACTIVE_CONTRACT_RECORDS,
    COALESCE(POS.COMPLETED_CONTRACT_RECORDS, 0) AS COMPLETED_CONTRACT_RECORDS,

    -- Credit card behavior
    COALESCE(CC.TOTAL_CREDIT_CARD_ACCOUNTS, 0) AS TOTAL_CREDIT_CARD_ACCOUNTS,
    COALESCE(CC.AVG_CREDIT_CARD_BALANCE, 0) AS AVG_CREDIT_CARD_BALANCE,
    COALESCE(CC.MAX_CREDIT_CARD_BALANCE, 0) AS MAX_CREDIT_CARD_BALANCE,
    COALESCE(CC.AVG_CREDIT_LIMIT, 0) AS AVG_CREDIT_LIMIT,
    COALESCE(CC.MAX_CREDIT_LIMIT, 0) AS MAX_CREDIT_LIMIT,
    COALESCE(CC.AVG_CREDIT_UTILIZATION, 0) AS AVG_CREDIT_UTILIZATION,
    COALESCE(CC.TOTAL_ATM_DRAWINGS, 0) AS TOTAL_ATM_DRAWINGS,
    COALESCE(CC.TOTAL_POS_DRAWINGS, 0) AS TOTAL_POS_DRAWINGS,
    COALESCE(CC.TOTAL_OTHER_DRAWINGS, 0) AS TOTAL_OTHER_DRAWINGS,
    COALESCE(CC.TOTAL_DRAWINGS, 0) AS TOTAL_DRAWINGS,
    COALESCE(CC.TOTAL_PAYMENTS, 0) AS TOTAL_PAYMENTS,
    COALESCE(CC.AVG_CURRENT_PAYMENT, 0) AS AVG_CURRENT_PAYMENT,
    COALESCE(CC.AVG_MINIMUM_INSTALLMENT, 0) AS AVG_MINIMUM_INSTALLMENT,
    COALESCE(CC.AVG_RECEIVABLE_PRINCIPAL, 0) AS AVG_RECEIVABLE_PRINCIPAL,
    COALESCE(CC.AVG_RECEIVABLE_AMOUNT, 0) AS AVG_RECEIVABLE_AMOUNT,
    COALESCE(CC.AVG_TOTAL_RECEIVABLE, 0) AS AVG_TOTAL_RECEIVABLE,
    COALESCE(CC.TOTAL_ATM_DRAWING_TRANSACTIONS, 0) AS TOTAL_ATM_DRAWING_TRANSACTIONS,
    COALESCE(CC.TOTAL_DRAWING_TRANSACTIONS, 0) AS TOTAL_DRAWING_TRANSACTIONS,
    COALESCE(CC.TOTAL_POS_DRAWING_TRANSACTIONS, 0) AS TOTAL_POS_DRAWING_TRANSACTIONS,
    COALESCE(CC.OVERDUE_MONTH_RECORDS, 0) AS OVERDUE_MONTH_RECORDS,
    COALESCE(CC.TOTAL_MONTHLY_RECORDS, 0) AS CREDIT_CARD_MONTHLY_RECORDS,

    -- Data ingestion tracking
    A.INSERTED_AT,
    A.UPDATED_AT

FROM {{ ref('stg_application_train') }} A

LEFT JOIN {{ ref('int_bureau_customer_summary') }} B
    ON A.CUSTOMER_ID = B.CUSTOMER_ID

LEFT JOIN {{ ref('int_previous_application_summary') }} P
    ON A.CUSTOMER_ID = P.CUSTOMER_ID

LEFT JOIN {{ ref('int_installment_payment_summary') }} I
    ON A.CUSTOMER_ID = I.CUSTOMER_ID

LEFT JOIN {{ ref('int_pos_cash_summary') }} POS
    ON A.CUSTOMER_ID = POS.CUSTOMER_ID

LEFT JOIN {{ ref('int_credit_card_summary') }} CC
    ON A.CUSTOMER_ID = CC.CUSTOMER_ID
