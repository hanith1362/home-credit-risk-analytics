SELECT
    -- Customer and loan identifiers
    SK_ID_CURR AS CUSTOMER_ID,
    SK_ID_PREV AS PREVIOUS_APPLICATION_ID,

    -- Monthly information
    MONTHS_BALANCE AS MONTH_OFFSET,
    NAME_CONTRACT_STATUS AS CONTRACT_STATUS,

    -- Credit card balance and limits
    AMT_BALANCE AS CURRENT_BALANCE,
    AMT_CREDIT_LIMIT_ACTUAL AS CREDIT_LIMIT,

    -- Drawing amounts
    AMT_DRAWINGS_ATM_CURRENT AS ATM_DRAWINGS_AMOUNT,
    AMT_DRAWINGS_CURRENT AS TOTAL_DRAWINGS_AMOUNT,
    AMT_DRAWINGS_OTHER_CURRENT AS OTHER_DRAWINGS_AMOUNT,
    AMT_DRAWINGS_POS_CURRENT AS POS_DRAWINGS_AMOUNT,

    -- Payment information
    AMT_INST_MIN_REGULARITY AS MINIMUM_INSTALLMENT_AMOUNT,
    AMT_PAYMENT_CURRENT AS CURRENT_PAYMENT_AMOUNT,
    AMT_PAYMENT_TOTAL_CURRENT AS TOTAL_PAYMENT_AMOUNT,

    -- Receivable information
    AMT_RECEIVABLE_PRINCIPAL AS RECEIVABLE_PRINCIPAL,
    AMT_RECIVABLE AS RECEIVABLE_AMOUNT,
    AMT_TOTAL_RECEIVABLE AS TOTAL_RECEIVABLE_AMOUNT,

    -- Transaction counts
    CNT_DRAWINGS_ATM_CURRENT AS ATM_DRAWINGS_COUNT,
    CNT_DRAWINGS_CURRENT AS TOTAL_DRAWINGS_COUNT,
    CNT_DRAWINGS_OTHER_CURRENT AS OTHER_DRAWINGS_COUNT,
    CNT_DRAWINGS_POS_CURRENT AS POS_DRAWINGS_COUNT,

    -- Installment information
    CNT_INSTALMENT_MATURE_CUM AS CUMULATIVE_MATURED_INSTALLMENTS,

    -- Delinquency information
    SK_DPD AS DAYS_PAST_DUE,
    SK_DPD_DEF AS DAYS_PAST_DUE_TOLERANCE,

    -- Ingestion tracking
    INSERTED_AT,
    UPDATED_AT

FROM {{ source('home_credit_raw', 'CREDIT_CARD_BALANCE') }}
